#[tokio::test]
async fn sqlite_drop_indexed_column() {
    let mut c = db("CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT, b TEXT); CREATE INDEX t_a ON t (a); INSERT INTO t VALUES (1, 'x', 'y');").await;
    // 인덱스를 남긴 채 컬럼만 지우면 거부
    let r = plan_and_apply(&mut c, "t", |b| {
        b.columns.remove(1);
    })
    .await;
    assert!(r.is_err());
    // 인덱스도 지우면 ALTER로 처리
    let p = plan_and_apply(&mut c, "t", |b| {
        b.columns.remove(1);
        b.indexes.clear();
    })
    .await
    .unwrap();
    assert_eq!(sqls(&p), [r#"DROP INDEX "t_a""#, r#"ALTER TABLE "t" DROP COLUMN "a""#]);
    assert_eq!(rows(&mut c, "SELECT b FROM t").await, [("y".to_string(),)]);
}

