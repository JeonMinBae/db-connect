#[tokio::test]
async fn sqlite_indexes_and_constraints() {
    let mut c = db("CREATE TABLE p (id INTEGER PRIMARY KEY); INSERT INTO p VALUES (1);
         CREATE TABLE t (id INTEGER PRIMARY KEY, pid INTEGER, n INT CONSTRAINT n_pos CHECK (n > 0), m INT);
         INSERT INTO t VALUES (1, 1, 5, 1), (2, 1, 6, 2);")
    .await;
    // 인덱스 추가는 CREATE INDEX만
    let p = plan_and_apply(&mut c, "t", |b| b.indexes.push(IndexDef { orig_name: None, ..idx("t_m", &["m"], true) })).await.unwrap();
    assert_eq!(sqls(&p), [r#"CREATE UNIQUE INDEX "t_m" ON "t" ("m")"#]);
    let s = load_sqlite(&mut c, "t").await.unwrap();
    assert_eq!(s.checks, [CheckDef { orig_name: Some("n_pos".into()), name: "n_pos".into(), expr: "n > 0".into() }]);
    // 외래 키·CHECK 추가는 재생성. 어긋나는 데이터가 없으면 반영된다
    plan_and_apply(&mut c, "t", |b| {
        b.foreign_keys.push(ForeignKeyDef { orig_name: None, on_delete: "CASCADE".into(), ..fk("", &["pid"], "p", &["id"]) });
        b.checks.push(CheckDef { orig_name: None, name: String::new(), expr: "m < 100".into() });
    })
    .await
    .unwrap();
    let s = load_sqlite(&mut c, "t").await.unwrap();
    assert_eq!(s.foreign_keys.len(), 1);
    assert_eq!(s.checks.iter().map(|c| c.expr.as_str()).collect::<Vec<_>>(), ["n > 0", "m < 100"]);
    assert!(s.indexes.iter().any(|i| i.name == "t_m" && i.unique), "재생성 뒤에도 인덱스가 남아야 한다");
    // CHECK를 어기는 데이터가 있으면 롤백
    let r = plan_and_apply(&mut c, "t", |b| b.checks[1].expr = "m < 2".into()).await;
    assert!(r.is_err());
    assert_eq!(load_sqlite(&mut c, "t").await.unwrap().checks[1].expr, "m < 100");
    // 기본키를 복합키로
    plan_and_apply(&mut c, "t", |b| b.primary_key = strs(&["id", "pid"])).await.unwrap();
    assert_eq!(load_sqlite(&mut c, "t").await.unwrap().primary_key, ["id", "pid"]);
    // 외래 키 삭제
    plan_and_apply(&mut c, "t", |b| b.foreign_keys.clear()).await.unwrap();
    assert!(load_sqlite(&mut c, "t").await.unwrap().foreign_keys.is_empty());
}

fn new_table() -> TableStructure {
    let mut id = new_col("id", "INTEGER");
    id.nullable = false;
    id.auto_increment = true;
    let mut name = new_col("name", "varchar(20)");
    name.nullable = false;
    name.default = Some("'x'".into());
    let mut t = st(vec![id, name, new_col("pid", "INTEGER")], &["id"]);
    t.indexes = vec![IndexDef { orig_name: None, ..idx("t_name", &["name"], true) }];
    t.foreign_keys = vec![ForeignKeyDef { orig_name: None, on_delete: "CASCADE".into(), ..fk("t_p", &["pid"], "p", &["id"]) }];
    t.checks = vec![CheckDef { orig_name: None, name: "t_ck".into(), expr: "length(name) > 0".into() }];
    t
}

#[test]
fn create_sql() {
    let t = new_table();
    assert_eq!(
        sqls(&plan_create(Driver::Postgres, Some("s"), "t", &t).unwrap()),
        [
            "CREATE TABLE \"s\".\"t\" (\n  \"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  \"name\" varchar(20) NOT NULL DEFAULT 'x',\n  \"pid\" INTEGER,\n  PRIMARY KEY (\"id\"),\n  CONSTRAINT \"t_ck\" CHECK (length(name) > 0),\n  CONSTRAINT \"t_p\" FOREIGN KEY (\"pid\") REFERENCES \"s\".\"p\" (\"id\") ON DELETE CASCADE\n)",
            "CREATE UNIQUE INDEX \"t_name\" ON \"s\".\"t\" (\"name\")",
        ]
    );
    assert_eq!(
        sqls(&plan_create(Driver::Mysql, Some("db"), "t", &t).unwrap()),
        ["CREATE TABLE `db`.`t` (\n  `id` INTEGER NOT NULL AUTO_INCREMENT,\n  `name` varchar(20) NOT NULL DEFAULT 'x',\n  `pid` INTEGER NULL,\n  PRIMARY KEY (`id`),\n  UNIQUE INDEX `t_name` (`name`),\n  CONSTRAINT `t_ck` CHECK (length(name) > 0),\n  CONSTRAINT `t_p` FOREIGN KEY (`pid`) REFERENCES `db`.`p` (`id`) ON DELETE CASCADE\n)"]
    );
    assert!(plan_create(Driver::Mysql, None, " ", &t).is_err());
    assert!(plan_create(Driver::Mysql, None, "t", &st(vec![], &[])).is_err());
    assert_eq!(plan_rename(Driver::Mysql, Some("db"), "a", "b").unwrap().sql, "RENAME TABLE `db`.`a` TO `db`.`b`");
    assert_eq!(plan_rename(Driver::Postgres, Some("s"), "a", "b").unwrap().sql, r#"ALTER TABLE "s"."a" RENAME TO "b""#);
    assert_eq!(plan_drop(Driver::Sqlite, Some("main"), "a").sql, r#"DROP TABLE "a""#);
}

#[tokio::test]
async fn sqlite_create_rename_drop() {
    let mut c = db("CREATE TABLE p (id INTEGER PRIMARY KEY); INSERT INTO p VALUES (1);").await;
    let mut t = new_table();
    t.columns[1].full_type = "TEXT".into();
    let p = plan_create(Driver::Sqlite, None, "t", &t).unwrap();
    let stmts: Vec<String> = p.statements.iter().map(|s| s.sql.clone()).collect();
    apply(&mut AnyConn::Lite(&mut c), &stmts).await.unwrap();
    let s = load_sqlite(&mut c, "t").await.unwrap();
    assert_eq!(s.columns.iter().map(|c| c.name.as_str()).collect::<Vec<_>>(), ["id", "name", "pid"]);
    assert!(s.columns[0].auto_increment && !s.columns[1].nullable);
    assert_eq!(s.columns[1].default.as_deref(), Some("'x'"));
    assert!(s.indexes.iter().any(|i| i.name == "t_name" && i.unique));
    assert_eq!(s.foreign_keys[0].on_delete, "CASCADE");
    assert_eq!(s.checks[0].name, "t_ck");
    // 이름 변경: 이 테이블을 참조하는 외래 키도 새 이름을 가리켜야 한다
    sqlx::raw_sql("CREATE TABLE child (tid INTEGER REFERENCES t(id)); CREATE VIEW tv AS SELECT id FROM t;").execute(&mut c).await.unwrap();
    let r = plan_rename(Driver::Sqlite, None, "t", "t2").unwrap();
    apply(&mut AnyConn::Lite(&mut c), &[r.sql]).await.unwrap();
    let parent: String = sqlx::query_scalar(r#"SELECT "table" FROM pragma_foreign_key_list('child')"#).fetch_one(&mut c).await.unwrap();
    assert_eq!(parent, "t2");
    assert_eq!(rows(&mut c, "SELECT CAST(count(*) AS TEXT) FROM tv").await, [("0".to_string(),)]);
    apply(&mut AnyConn::Lite(&mut c), &[plan_drop(Driver::Sqlite, None, "child").sql]).await.unwrap();
    assert!(load_sqlite(&mut c, "child").await.unwrap().columns.is_empty());
}
