fn col(name: &str, ty: &str) -> ColumnDef {
    ColumnDef { orig_name: Some(name.into()), name: name.into(), full_type: ty.into(), nullable: true, ..Default::default() }
}
fn new_col(name: &str, ty: &str) -> ColumnDef {
    ColumnDef { orig_name: None, ..col(name, ty) }
}
fn strs(v: &[&str]) -> Vec<String> {
    v.iter().map(|s| s.to_string()).collect()
}
fn st(cols: Vec<ColumnDef>, pk: &[&str]) -> TableStructure {
    TableStructure { columns: cols, primary_key: strs(pk), ..Default::default() }
}
fn idx(name: &str, cols: &[&str], unique: bool) -> IndexDef {
    IndexDef { orig_name: Some(name.into()), name: name.into(), columns: strs(cols), unique, ..Default::default() }
}
fn fk(name: &str, cols: &[&str], rt: &str, rc: &[&str]) -> ForeignKeyDef {
    ForeignKeyDef {
        orig_name: Some(name.into()),
        name: name.into(),
        columns: strs(cols),
        ref_schema: None,
        ref_table: rt.into(),
        ref_columns: strs(rc),
        on_update: "NO ACTION".into(),
        on_delete: "NO ACTION".into(),
    }
}
fn sqls(p: &DdlPlan) -> Vec<&str> {
    p.statements.iter().map(|s| s.sql.as_str()).collect()
}

#[test]
fn pg_columns() {
    let a = st(vec![col("id", "integer"), col("name", "text"), col("old", "text")], &["id"]);
    let mut b = a.clone();
    b.columns.remove(2);
    b.columns[1].name = "full name".into();
    b.columns[1].full_type = "varchar(100)".into();
    b.columns[1].nullable = false;
    b.columns[1].default = Some("'x'".into());
    b.columns[0].auto_increment = true;
    b.columns[0].nullable = false;
    b.columns.push(ColumnDef { nullable: false, default: Some("0".into()), comment: Some("it's".into()), ..new_col("qty", "int") });
    let p = plan_alter(Driver::Postgres, Some("public"), "t", &a, &b, None).unwrap();
    assert_eq!(
        sqls(&p),
        [
            r#"ALTER TABLE "public"."t" DROP COLUMN "old""#,
            r#"ALTER TABLE "public"."t" ALTER COLUMN "id" SET NOT NULL"#,
            r#"ALTER TABLE "public"."t" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY"#,
            r#"ALTER TABLE "public"."t" RENAME COLUMN "name" TO "full name""#,
            r#"ALTER TABLE "public"."t" ALTER COLUMN "full name" TYPE varchar(100) USING "full name"::varchar(100)"#,
            r#"ALTER TABLE "public"."t" ALTER COLUMN "full name" SET DEFAULT 'x'"#,
            r#"ALTER TABLE "public"."t" ALTER COLUMN "full name" SET NOT NULL"#,
            r#"ALTER TABLE "public"."t" ADD COLUMN "qty" int NOT NULL DEFAULT 0"#,
            r#"COMMENT ON COLUMN "public"."t"."qty" IS 'it''s'"#,
        ]
    );
    assert!(p.statements[0].destructive && p.statements[4].destructive && !p.statements[3].destructive);
    assert_eq!(p.warnings.len(), 2);
    assert!(p.warnings[0].contains("old") && p.warnings[1].contains("text → varchar(100)"));
    let mut moved = a.clone();
    moved.columns.swap(0, 1);
    assert!(plan_alter(Driver::Postgres, Some("public"), "t", &a, &moved, None).is_err());
    assert!(plan_alter(Driver::Postgres, Some("public"), "t", &a, &a, None).unwrap().statements.is_empty());
}

#[test]
fn pg_constraints() {
    let mut a = st(vec![col("id", "int"), col("a", "int"), col("b", "int"), col("pid", "int")], &["id"]);
    a.primary_key_name = Some("t_pkey".into());
    a.indexes = vec![idx("t_a", &["a"], false), IndexDef { constraint: true, ..idx("t_b_key", &["b"], true) }];
    a.foreign_keys = vec![fk("t_pid_fk", &["pid"], "p", &["id"])];
    a.checks = vec![CheckDef { orig_name: Some("t_a_check".into()), name: "t_a_check".into(), expr: "a > 0".into() }];
    let mut b = a.clone();
    // 컬럼 이름만 바뀌면 외래 키는 그대로 (초안은 새 이름을 쓴다)
    b.columns[3].name = "parent".into();
    b.foreign_keys[0].columns = strs(&["parent"]);
    // 인덱스 컬럼 변경, UNIQUE 제약 삭제, 새 인덱스, 기본키 변경, CHECK 식 변경
    b.indexes[0].columns = strs(&["a", "b"]);
    b.indexes.remove(1);
    b.indexes.push(IndexDef { orig_name: None, ..idx("t_new", &["b"], true) });
    b.primary_key = strs(&["id", "a"]);
    b.checks[0].expr = "a >= 0".into();
    let p = plan_alter(Driver::Postgres, Some("s"), "t", &a, &b, None).unwrap();
    assert_eq!(
        sqls(&p),
        [
            r#"ALTER TABLE "s"."t" DROP CONSTRAINT "t_a_check""#,
            r#"ALTER TABLE "s"."t" DROP CONSTRAINT "t_b_key""#,
            r#"DROP INDEX "s"."t_a""#,
            r#"ALTER TABLE "s"."t" DROP CONSTRAINT "t_pkey""#,
            r#"ALTER TABLE "s"."t" RENAME COLUMN "pid" TO "parent""#,
            r#"ALTER TABLE "s"."t" ADD PRIMARY KEY ("id", "a")"#,
            r#"CREATE INDEX "t_a" ON "s"."t" ("a", "b")"#,
            r#"CREATE UNIQUE INDEX "t_new" ON "s"."t" ("b")"#,
            r#"ALTER TABLE "s"."t" ADD CONSTRAINT "t_a_check" CHECK (a >= 0)"#,
        ]
    );
    // 외래 키 동작·참조 스키마 변경은 지우고 다시 만든다
    let mut c = a.clone();
    c.foreign_keys[0].on_delete = "CASCADE".into();
    c.foreign_keys[0].ref_schema = Some("other".into());
    assert_eq!(
        sqls(&plan_alter(Driver::Postgres, Some("s"), "t", &a, &c, None).unwrap()),
        [
            r#"ALTER TABLE "s"."t" DROP CONSTRAINT "t_pid_fk""#,
            r#"ALTER TABLE "s"."t" ADD CONSTRAINT "t_pid_fk" FOREIGN KEY ("pid") REFERENCES "other"."p" ("id") ON DELETE CASCADE"#,
        ]
    );
}

#[test]
fn mysql_one_statement() {
    let mut name = col("name", "varchar(50)");
    name.charset = Some("latin1".into());
    name.collation = Some("latin1_swedish_ci".into());
    name.comment = Some("a\\b".into());
    let mut ts = col("ts", "timestamp");
    ts.default = Some("CURRENT_TIMESTAMP".into());
    ts.on_update = Some("CURRENT_TIMESTAMP".into());
    let a = st(vec![col("id", "int"), name, ts, col("gone", "int")], &["id"]);
    let mut b = a.clone();
    b.columns.remove(3);
    b.columns[1].name = "nm".into();
    b.columns[2].nullable = false;
    b.columns.insert(1, new_col("x`y", "int"));
    let p = plan_alter(Driver::Mysql, Some("db"), "t", &a, &b, None).unwrap();
    assert_eq!(
        sqls(&p),
        ["ALTER TABLE `db`.`t`\n  DROP COLUMN `gone`,\n  ADD COLUMN `x``y` int NULL AFTER `id`,\n  CHANGE COLUMN `name` `nm` varchar(50) CHARACTER SET latin1 COLLATE latin1_swedish_ci NULL COMMENT 'a\\\\b' AFTER `x``y`,\n  MODIFY COLUMN `ts` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP AFTER `nm`"]
    );
    assert!(p.statements[0].destructive);
    let mut first = a.clone();
    first.columns.swap(0, 1);
    assert_eq!(
        sqls(&plan_alter(Driver::Mysql, Some("db"), "t", &a, &first, None).unwrap())[0].lines().nth(1).unwrap().trim(),
        "MODIFY COLUMN `name` varchar(50) CHARACTER SET latin1 COLLATE latin1_swedish_ci NULL COMMENT 'a\\\\b' FIRST,"
    );
    let mut num = a.clone();
    num.columns[1].full_type = "int".into();
    assert!(sqls(&plan_alter(Driver::Mysql, None, "t", &a, &num, None).unwrap())[0].contains("MODIFY COLUMN `name` int NULL COMMENT"));
}

#[test]
fn mysql_constraints() {
    let mut a = st(vec![col("id", "int"), col("a", "int"), col("pid", "int")], &["id"]);
    a.indexes = vec![idx("ix_a", &["a"], false)];
    a.foreign_keys = vec![fk("fk_p", &["pid"], "p", &["id"])];
    a.checks = vec![CheckDef { orig_name: Some("ck".into()), name: "ck".into(), expr: "`a` > 0".into() }];
    let mut b = a.clone();
    b.primary_key = strs(&["id", "a"]);
    b.indexes[0].unique = true;
    b.checks.clear();
    b.checks.push(CheckDef { orig_name: None, name: String::new(), expr: "a < 10".into() });
    let p = plan_alter(Driver::Mysql, Some("db"), "t", &a, &b, None).unwrap();
    assert_eq!(
        sqls(&p),
        ["ALTER TABLE `db`.`t`\n  DROP CONSTRAINT `ck`,\n  DROP INDEX `ix_a`,\n  DROP PRIMARY KEY,\n  ADD PRIMARY KEY (`id`, `a`),\n  ADD UNIQUE INDEX `ix_a` (`a`),\n  ADD CHECK (a < 10)"]
    );
    // 같은 이름의 외래 키를 다시 만들면 지우는 문장을 앞에 따로 둔다
    let mut c = a.clone();
    c.foreign_keys[0].on_delete = "SET NULL".into();
    assert_eq!(
        sqls(&plan_alter(Driver::Mysql, Some("db"), "t", &a, &c, None).unwrap()),
        [
            "ALTER TABLE `db`.`t`\n  DROP FOREIGN KEY `fk_p`",
            "ALTER TABLE `db`.`t`\n  ADD CONSTRAINT `fk_p` FOREIGN KEY (`pid`) REFERENCES `db`.`p` (`id`) ON DELETE SET NULL",
        ]
    );
}

#[test]
fn validation() {
    let a = st(vec![col("id", "int")], &[]);
    let dup = st(vec![col("id", "int"), new_col("ID", "int")], &[]);
    assert!(plan_alter(Driver::Mysql, None, "t", &a, &dup, None).is_err());
    let empty = st(vec![new_col("x", " ")], &[]);
    assert!(plan_alter(Driver::Postgres, None, "t", &a, &empty, None).is_err());
    let mut g = a.clone();
    g.columns[0].generated = true;
    let mut g2 = g.clone();
    g2.columns[0].name = "id2".into();
    assert!(plan_alter(Driver::Postgres, None, "t", &g, &g2, None).is_err());
    // 삭제한 컬럼을 쓰는 인덱스·기본키
    let mut b = st(vec![col("id", "int"), col("a", "int")], &["id"]);
    b.indexes = vec![idx("ix", &["a"], false)];
    let mut no_a = b.clone();
    no_a.columns.remove(1);
    let e = plan_alter(Driver::Postgres, None, "t", &b, &no_a, None).unwrap_err().to_string();
    assert!(e.contains("인덱스 ix"), "{e}");
    let mut no_id = b.clone();
    no_id.columns.remove(0);
    no_id.indexes.clear();
    assert!(plan_alter(Driver::Postgres, None, "t", &b, &no_id, None).unwrap_err().to_string().contains("기본키"));
    // 외래 키 컬럼 수
    let mut bad = b.clone();
    bad.foreign_keys = vec![ForeignKeyDef { orig_name: None, ..fk("f", &["a"], "p", &["x", "y"]) }];
    assert!(plan_alter(Driver::Postgres, None, "t", &b, &bad, None).is_err());
}

#[test]
fn sqlite_scanner() {
    let sql = "CREATE TABLE \"a(b\" (x 'CHECK', y INT /* COLLATE */ -- GENERATED\n, [z)] TEXT) WITHOUT ROWID;";
    assert_eq!(sqlite_words(sql), ["CREATE", "TABLE", "X", "Y", "INT", "TEXT", "WITHOUT", "ROWID"]);
    assert_eq!(sqlite_tail(sql), " WITHOUT ROWID");
    assert_eq!(sqlite_tail("CREATE TABLE t (a, b)"), "");
    let checks = sqlite_checks("CREATE TABLE t (a INT CHECK (a > 0), b TEXT, CONSTRAINT \"b len\" CHECK (length(b) < 5 AND b <> ')'), CHECK(a<>b))");
    assert_eq!(
        checks,
        [(None, "a > 0".to_string()), (Some("b len".to_string()), "length(b) < 5 AND b <> ')'".to_string()), (None, "a<>b".to_string())]
    );
}

async fn db(sql: &str) -> SqliteConnection {
    let mut c = SqliteConnection::connect("sqlite::memory:").await.unwrap();
    sqlx::raw_sql("PRAGMA foreign_keys = ON").execute(&mut c).await.unwrap();
    sqlx::raw_sql(sql).execute(&mut c).await.unwrap();
    c
}

async fn plan_and_apply(c: &mut SqliteConnection, table: &str, edit: impl FnOnce(&mut TableStructure)) -> AppResult<DdlPlan> {
    let a = load_sqlite(c, table).await.unwrap();
    let aux = load_sqlite_aux(c, table).await.unwrap();
    let mut b = a.clone();
    edit(&mut b);
    let p = plan_alter(Driver::Sqlite, None, table, &a, &b, Some(&aux))?;
    let stmts: Vec<String> = p.statements.iter().map(|s| s.sql.clone()).collect();
    apply(&mut AnyConn::Lite(c), &stmts).await?;
    Ok(p)
}

async fn rows(c: &mut SqliteConnection, sql: &str) -> Vec<(String,)> {
    sqlx::query_as(sql).fetch_all(c).await.unwrap()
}

